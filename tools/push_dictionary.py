#!/usr/bin/env python3
"""Generate src/waterlink/push_dictionary.h, the zstd dictionary `link push` uses.

Both ends of a push run the same moonwater client, so both hold the same
dictionary, built into the image. It is a trained zstd dictionary (RFC 8878
format, with its Huffman and FSE tables), trained by the zstd command line on
1 KiB chunks of the source tree both ends share: the help page at the top of
src/waterlink/command.c, the link's verbs, messages and log formats, the
moonwater help and settings strings, and the repository's own prose and code.
Trained on those, the table gives small text its entropy tables as well as its
matches; held-out text of 512 bytes came out 13 percent smaller, 2 KiB 6 percent
and 8 KiB 3 percent (measured with Python's zstd against a dictionary-free
encode; a raw content dictionary of the same text gained nothing).

The output is deterministic for a given tree and zstd version. The wire carries
PUSH_DICTIONARY_ID, the dictionary's own zstd id, so a receiver whose table
differs refuses the push instead of decoding it.

Regenerate after any change to those sources, from the repository root, with a
zstd command line (1.4 or later) on PATH:

    python3 tools/push_dictionary.py > src/waterlink/push_dictionary.h
"""

import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DICT_SIZE = 32768
CHUNK = 1024
CHUNK_MIN = 256
SCAN_LIMIT = 64 * 1024  # per file: the first 64 KiB of each training file
ZSTD_DICT_MAGIC = 0xEC30A437

TRAINING_GLOBS = [
    "src/waterlink/*.c",
    "src/moonwater/*.c",
    "src/sh/*.c",
    "*.md",
    "docs/*.md",
]


def training_files():
    found = set()
    for pattern in TRAINING_GLOBS:
        for path in ROOT.glob(pattern):
            if path.is_file():
                found.add(path)
    return sorted(found)


def write_samples(directory):
    """Cut the training files into CHUNK-byte samples; returns their paths."""
    samples = []
    for path in training_files():
        data = path.read_bytes()[:SCAN_LIMIT]
        for start in range(0, len(data), CHUNK):
            chunk = data[start:start + CHUNK]
            if len(chunk) < CHUNK_MIN:
                continue
            sample = os.path.join(directory, "s%05d" % len(samples))
            with open(sample, "wb") as out:
                out.write(chunk)
            samples.append(sample)
    return samples


def train(samples, directory):
    zstd = shutil.which("zstd")
    if zstd is None:
        sys.exit("push_dictionary: a zstd command line is needed on PATH to train the dictionary")
    out = os.path.join(directory, "push.dict")
    result = subprocess.run(
        [zstd, "--train", "--maxdict=%d" % DICT_SIZE, "-q", "-o", out] + samples,
        capture_output=True, text=True)
    if result.returncode != 0 or not os.path.exists(out):
        sys.exit("push_dictionary: zstd --train failed: " + result.stderr.strip())
    return Path(out).read_bytes()


def dictionary_id(data):
    if len(data) < 8 or struct.unpack("<I", data[:4])[0] != ZSTD_DICT_MAGIC:
        sys.exit("push_dictionary: the trained dictionary has no zstd header")
    return struct.unpack("<I", data[4:8])[0]


def emit(data):
    ident = dictionary_id(data)
    out = []
    out.append("/*")
    out.append("        Generated by tools/push_dictionary.py from the moonwater source tree;")
    out.append("        do not edit. Regenerate from the repository root with")
    out.append("")
    out.append("                python3 tools/push_dictionary.py > src/waterlink/push_dictionary.h")
    out.append("")
    out.append("        A trained zstd dictionary: both ends of `link push` load this table, and")
    out.append("        the push request carries PUSH_DICTIONARY_ID, so a receiver with another")
    out.append("        table refuses the push instead of decoding it wrongly.")
    out.append("*/")
    out.append("")
    out.append("#define PUSH_DICTIONARY_SIZE %d" % len(data))
    out.append("#define PUSH_DICTIONARY_ID 0x%08Xu" % ident)
    out.append("")
    out.append("static p8 push_dictionary[PUSH_DICTIONARY_SIZE] = {")
    for start in range(0, len(data), 16):
        row = ", ".join("0x%02x" % b for b in data[start:start + 16])
        out.append("        " + row + ("," if start + 16 < len(data) else ""))
    out.append("};")
    out.append("")
    return "\n".join(out)


def main():
    with tempfile.TemporaryDirectory() as directory:
        samples = write_samples(directory)
        if not samples:
            sys.exit("push_dictionary: no training text found under " + str(ROOT))
        data = train(samples, directory)
    sys.stdout.write(emit(data))


if __name__ == "__main__":
    main()
