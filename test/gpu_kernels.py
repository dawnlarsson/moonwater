#!/usr/bin/env python3
"""Hold the build's assembler for the GPU's kernels to LLVM's.

    python3 test/gpu_kernels.py ASM INC     assemble ASM with llvm-mc and fail unless INC (what
                                            `build gpu-kernels ASM INC` wrote) holds exactly the
                                            same words, kernel by kernel
    python3 test/gpu_kernels.py --print ASM the arrays llvm-mc makes of ASM, in the form the
                                            build writes them (a hand build's artifacts/gpu_kernels.inc),
                                            with the FNV-1a 64 of ASM's bytes (GPU_KERNELS_ASM_HASH)
    python3 test/gpu_kernels.py --hash ASM  the line src/canvas/gpu_asm.hash holds: ASM's FNV-1a 64
                                            (GPU_ASM_HASH), which gpu.c holds the included kernels'
                                            GPU_KERNELS_ASM_HASH to, so kernels made from another
                                            gpu.asm are a compile error, not a card that runs them
    python3 test/gpu_kernels.py --print-intel SRC
                                            the array gpu_i915_gen9.inc holds, made from SRC
                                            (src/canvas/gpu_i915.asm) the way `build gpu-i915`
                                            writes it: a hand build is
                                            python3 test/gpu_kernels.py --print-intel src/canvas/gpu_i915.asm > artifacts/gpu_i915_gen9.inc
    python3 test/gpu_kernels.py --intel-gen12 SRC.iga
                                            SRC.iga (a kernel's Gen9 assembly, src/canvas/gpu_i915_NAME.iga)
                                            in Gen12's syntax: what iga64 -a -p=12p1 -Xauto-deps
                                            -Xforce-no-compact assembles into the words of `kernel NAME12`
    python3 test/gpu_kernels.py --probe     whether the llvm-mc at hand writes the words the build's
                                            assembler is held to, where LLVM's versions differ: 0
                                            when it does, 2 and why when it does not

    python3 test/gpu_kernels.py --chips ASM CHIP...
                                            fail unless llvm-mc makes of ASM, for each CHIP (gfx1010,
                                            gfx1012, gfx1030), the words it makes for gfx1036: the
                                            kernels are then code for those chips as they stand. LLVM
                                            is compared with itself here, so any LLVM will do

Where LLVM's versions differ. An instruction in the three-source encoding that takes two sources
has a field for the third that the chip does not read: the build's assembler writes the constant 0
there (0x80), as the clang that made the kernels in src/canvas/gpu_compiled.inc did, and LLVM 18 to 21 write
the register 0. An LLVM that writes anything but 0x80 cannot be compared word for word, and the
probe says so; nothing is compared with it and nothing passes. (Forward progress, the first
resource word's top bit, is clear by default before LLVM 21 and set from it: the kernels' blocks
ask for it, so that is the same on all of them.)

The kernels are src/canvas/gpu.asm (what ships) and test/gpu_stress.asm (every instruction in every
operand form the build's assembler takes). Each kernel is its two resource words and then its code,
read out of the object llvm-mc and ld.lld make: the kernel descriptor's rsrc1 and rsrc2, and the
bytes between the kernel's symbol and its size. A kernel that needs scratch is refused, as the
dispatch gives none. Needs llvm-mc and ld.lld with the AMDGPU target.
"""
import pathlib
import re
import shutil
import struct
import subprocess
import sys
import tempfile

MC = ['-triple=amdgcn-amd-amdhsa', '-mcpu=gfx1036', '-mattr=+wavefrontsize64,-wavefrontsize32']


def tool(name):
    found = shutil.which(name)
    if not found:
        sys.exit('%s: not found' % name)
    return found


def _rewrite_gfx12_waitcnt(m):
    parts = [p.strip() for p in re.split(r'[&,\s]+', m.group(1).strip()) if p.strip()]
    out = []
    for p in parts:
        km = re.fullmatch(r'(\w+)\((\d+)\)', p)
        if not km:
            return m.group(0)
        name, val = km.group(1), km.group(2)
        if name == 'vmcnt':
            out.append('\ts_wait_loadcnt %s' % val)
        elif name == 'expcnt':
            out.append('\ts_wait_expcnt %s' % val)
        elif name == 'lgkmcnt':
            out.append('\ts_wait_kmcnt %s' % val)
            out.append('\ts_wait_dscnt %s' % val)
    return '\n'.join(out)


def _rewrite_gfx12_image(m):
    v0 = int(m.group(2))
    rest = re.sub(r'\s+unorm\b', '', m.group(3))
    return '%s, [v%d, v%d], %s' % (m.group(1), v0, v0 + 1, rest)


# gfx9 (Vega, and the Raven to Cezanne APUs): LLVM's names for its chips, the first the one the others are held to.
GFX9 = ('gfx900', 'gfx902', 'gfx904', 'gfx906', 'gfx909', 'gfx90c')
GFX9_NAMES = {'v_add_nc_u32': 'v_add_u32', 'v_sub_nc_u32': 'v_sub_u32', 'v_subrev_nc_u32': 'v_subrev_u32', 'v_add_co_ci_u32': 'v_addc_co_u32'}
GFX9_CARRIES = ('v_mad_u64_u32', 'v_add_co_u32', 'v_addc_co_u32')  # their second operand is a destination too
GFX9_FLOATS = (0x3f000000, 0xbf000000, 0x3f800000, 0xbf800000, 0x40000000, 0xc0000000, 0x40800000, 0xc0800000, 0x3e22f983)


def _statements(src):
    """The text's statements with its macros and its .irp blocks expanded, as the build's assembler expands them: one a line,
    comments gone, a label on a line of its own."""
    macros = {}

    def run(lines, out, depth=0):
        if depth > 8:
            sys.exit('expansions nested too deep')
        at = 0
        while at < len(lines):
            line = lines[at].split(';', 1)[0].strip()
            at += 1
            if not line:
                continue
            word = line.split()[0]
            if word in ('.macro', '.irp'):
                close, depth_in, body = ('.endm' if word == '.macro' else '.endr'), 1, []
                while True:
                    if at >= len(lines):
                        sys.exit('a block that is never closed: %s' % line)
                    inner = lines[at].split(';', 1)[0].strip()
                    first = inner.split()[0] if inner else ''
                    at += 1
                    if first == word:
                        depth_in += 1
                    elif first == close:
                        depth_in -= 1
                        if not depth_in:
                            break
                    body.append(lines[at - 1])
                rest = line[len(word):].strip()
                if word == '.macro':
                    name, _, params = rest.partition(' ')
                    macros[name.rstrip(',')] = ([q.strip() for q in params.split(',') if q.strip()], body)
                else:
                    variable, _, values = rest.partition(',')
                    for value in values.split(','):
                        run([substitute(b, [variable.strip()], [value.strip()]) for b in body], out, depth + 1)
                continue
            if word in macros:
                params, body = macros[word]
                values = _operands(line[len(word):])
                if len(values) != len(params):
                    sys.exit('the wrong number of arguments to the macro %s: %s' % (word, line))
                run([substitute(b, params, values) for b in body], out, depth + 1)
                continue
            while re.match(r'^[\w.$]+:', line):
                label, _, line = line.partition(':')
                out.append(label + ':')
                line = line.strip()
            if line:
                out.append(line)

    def substitute(line, names, values):
        return re.sub(r'\\([A-Za-z0-9_$]+)', lambda m: values[names.index(m.group(1))] if m.group(1) in names else m.group(0), line)

    out = []
    run(src.splitlines(), out)
    return out


def _operands(text):
    parts, depth, start = [], 0, 0
    text = text.strip()
    if not text:
        return []
    for at, c in enumerate(text + ','):
        if c in '[(':
            depth += 1
        elif c in '])' and depth:
            depth -= 1
        elif c == ',' and not depth:
            parts.append(text[start:at].strip())
            start = at + 1
    return parts


def _literal(word):
    """A number that is no inline constant of a 32-bit operand: its 32 bits, or None."""
    if not re.fullmatch(r'-?(0x[0-9a-fA-F]+|[0-9]+)', word):
        return None
    value = int(word, 0)
    if -16 <= value <= 64 or -16 <= value - (1 << 32) <= -1 or (value & 0xffffffff) in GFX9_FLOATS:
        return None
    return value & 0xffffffff


def gfx9(src, chip):
    """The text as a gfx9 chip's LLVM takes it, and what gfx9's long encodings do not take said the build's assembler's way
    (src/build/gpuasm.c, gpuasm_lowered): LLVM names each instruction it refuses, for a literal there or for two scalar registers,
    and the literal becomes a register of the kernel's own loaded at its label, the second scalar a register moved to just before."""
    lines = []
    for line in _statements(src):
        word = line.split()[0]
        if word == '.amdgcn_target':
            line = line.replace('--gfx1036"', '--%s"' % chip)
        if word in ('.amdhsa_wavefront_size32', '.amdhsa_forward_progress'):
            continue  # gfx10's: gfx9's waves are 64 lanes and its first resource word has no such bit
        base, suffix = (word[:-4], word[-4:]) if word.endswith(('_e64', '_e32')) else (word, '')
        if base in GFX9_NAMES:
            line = GFX9_NAMES[base] + suffix + line[len(word):]
        lines.append(line.replace(' dim:SQ_RSRC_IMG_2D', ''))
    names = [l.split()[1] for l in lines if l.split()[0] == '.amdhsa_kernel']
    span, inside = {}, None
    for at, line in enumerate(lines):
        if line.endswith(':') and line[:-1] in names:
            inside = line[:-1]
            span[inside] = [at, None]
        elif inside and re.match(r'\.size\s+%s\s*,' % re.escape(inside), line):
            span[inside][1], inside = at, None
    kernel_of = {}
    for name, (first, last) in span.items():
        for at in range(first, last if last is not None else first):
            kernel_of[at] = name
    pooled, moved = {}, {}  # a statement's literal (its operand's index and its 32 bits); its scalar moved (the operand's index)
    work = pathlib.Path(tempfile.mkdtemp())
    try:
        for attempt in range(8):
            pools = {name: [] for name in names}
            for at in sorted(pooled):
                if pooled[at][1] not in pools[kernel_of[at]]:
                    pools[kernel_of[at]].append(pooled[at][1])
            moves = {name: any(kernel_of[at] == name for at in moved) for name in names}
            vgprs, block = {}, None
            for line in lines:
                if line.split()[0] == '.amdhsa_kernel':
                    block = line.split()[1]
                elif line.split()[0] == '.amdhsa_next_free_vgpr':
                    vgprs[block] = int(line.split()[1])
            out, where, block = [], [], None
            for at, line in enumerate(lines):
                word = line.split()[0]
                name = kernel_of.get(at)
                if word == '.amdhsa_kernel':
                    block = line.split()[1]
                elif word == '.amdhsa_next_free_vgpr':
                    line = '%s %d' % (word, vgprs[block] + len(pools[block]) + (1 if moves[block] else 0))
                if at in pooled or at in moved:
                    ops, tail = _operands(line[len(word):]), ''
                    m = re.match(r'^(.*?)((?:\s+clamp)?)$', ops[-1])
                    ops[-1], tail = m.group(1), m.group(2)
                    if at in pooled:
                        ops[pooled[at][0]] = 'v%d' % (vgprs[name] + pools[name].index(pooled[at][1]))
                    if at in moved:
                        spare = vgprs[name] + len(pools[name])
                        out.append('v_mov_b32 v%d, %s' % (spare, ops[moved[at]]))
                        where.append(at)
                        ops = ['v%d' % spare if k >= 1 and o == ops[moved[at]] else o for k, o in enumerate(ops)]
                    line = '%s %s%s' % (word, ', '.join(ops), tail)
                out.append(line)
                where.append(at)
                if line.endswith(':') and line[:-1] in pools:
                    for k, value in enumerate(pools[line[:-1]]):
                        out.append('v_mov_b32 v%d, 0x%x' % (vgprs[line[:-1]] + k, value))
                        where.append(at)
            text = '\n'.join(out) + '\n'
            (work / 'k.asm').write_text(text)
            made = subprocess.run([tool('llvm-mc'), '-triple=amdgcn-amd-amdhsa', '-mcpu=' + chip, '-filetype=obj', str(work / 'k.asm'), '-o', str(work / 'k.o')],
                                  capture_output=True, text=True)
            if not made.returncode:
                return text
            errors = re.findall(r'k\.asm:(\d+):\d+: error: ([^\n]*)', made.stderr)
            if not errors:
                sys.exit('llvm-mc for %s: %s' % (chip, made.stderr.strip()[:400]))
            fresh = 0
            for number, what in errors:
                at = where[int(number) - 1]
                word = lines[at].split()[0]
                ops = _operands(lines[at][len(word):])
                ops[-1] = re.sub(r'\s+clamp$', '', ops[-1])
                first = 2 if (word[:-4] if word.endswith('_e64') else word) in GFX9_CARRIES else 1
                if at not in kernel_of:
                    sys.exit('%s: outside a kernel, %s: %s' % (chip, what, lines[at]))
                if what.startswith('literal operands are not supported') and at not in pooled:
                    found = [(k, _literal(o)) for k, o in enumerate(ops) if k >= first and _literal(o) is not None]
                    if len(found) != 1:
                        sys.exit('%s: %s: %s' % (chip, what, lines[at]))
                    pooled[at], fresh = found[0], fresh + 1
                elif 'violates constant bus restrictions' in what and at not in moved:
                    scalars = [(k, o) for k, o in enumerate(ops) if k >= first and re.fullmatch(r's\d+', o)]
                    pair = any(k >= first and (re.fullmatch(r's\[\d+:\d+\]', o) or o in ('vcc', 'exec')) for k, o in enumerate(ops))
                    others = [(k, o) for k, o in scalars if pair or o != scalars[0][1]]
                    if not others or len(set(o for _, o in others)) != 1:
                        sys.exit('%s: %s: %s' % (chip, what, lines[at]))
                    moved[at], fresh = others[0][0], fresh + 1
                elif at not in pooled and at not in moved:
                    sys.exit('llvm-mc for %s: %s: %s' % (chip, what, lines[at]))
            if not fresh:
                sys.exit('llvm-mc for %s still refuses: %s' % (chip, made.stderr.strip()[:400]))
        sys.exit('llvm-mc for %s: not settled' % chip)
    finally:
        shutil.rmtree(work, ignore_errors=True)


def build(asm, chip=None):
    work = pathlib.Path(tempfile.mkdtemp())
    mc = MC
    if chip in GFX9:
        (work / 'k.asm').write_text(gfx9(pathlib.Path(asm).read_text(), chip))
        asm, mc = work / 'k.asm', ['-triple=amdgcn-amd-amdhsa', '-mcpu=' + chip]
    elif chip:
        #   the same text for another chip: the target line and the processor name it, plus GFX11+/12 directive & waitcnt lowering
        src = pathlib.Path(asm).read_text().replace('--gfx1036"', '--%s"' % chip)
        if chip.startswith('gfx11') or chip.startswith('gfx12'):
            src = src.replace('.amdhsa_user_sgpr_private_segment_buffer 1', '.amdhsa_user_sgpr_count 6')
        if chip.startswith('gfx12'):
            src = re.sub(r'^[ \t]*s_waitcnt[ \t]+(.+)$', _rewrite_gfx12_waitcnt, src, flags=re.M)
            src = re.sub(r'(image_load[ \t]+v(?:\[\d+:\d+\]|\d+)),[ \t]*v\[(\d+):\d+\],[ \t]*(s\[\d+:\d+\].*)', _rewrite_gfx12_image, src)
        (work / 'k.asm').write_text(src)
        asm, mc = work / 'k.asm', [w.replace('gfx1036', chip) for w in MC]
    subprocess.run([tool('llvm-mc')] + mc + ['-filetype=obj', str(asm), '-o', str(work / 'k.o')], check=True)
    subprocess.run([tool('ld.lld'), '-shared', str(work / 'k.o'), '-o', str(work / 'k.so')], check=True)
    data = (work / 'k.so').read_bytes()
    shutil.rmtree(work)
    return data


PROBE = '''.amdgcn_target "amdgcn-amd-amdhsa--gfx1036"
.text
.globl probe
.p2align 8
.type probe,@function
probe:
	v_pk_min_u16 v1, v2, v3
	s_endpgm
.size probe, .-probe
.rodata
.p2align 6
.amdhsa_kernel probe
	.amdhsa_next_free_vgpr 8
	.amdhsa_next_free_sgpr 24
	.amdhsa_wavefront_size32 0
	.amdhsa_forward_progress 1
.end_amdhsa_kernel
'''


def probe():
    work = pathlib.Path(tempfile.mkdtemp())
    (work / 'probe.asm').write_text(PROBE)
    try:
        words = kernels(build(work / 'probe.asm'))[0][1]
        words9 = kernels(build(work / 'probe.asm', GFX9[0]))[0][1]
    finally:
        shutil.rmtree(work, ignore_errors=True)
    version = subprocess.run([tool('llvm-mc'), '--version'], capture_output=True, text=True).stdout
    version = (re.search(r'version (\S+)', version) or [None, 'of no version it says'])[1]
    third = words[3] >> 18 & 0x1ff
    if third != 0x80:
        print('llvm-mc %s writes 0x%02x in the third source a two-source instruction does not have (v_pk_min_u16 v1, v2, v3 is %08x %08x), '
              'the build\'s assembler the constant 0, 0x80: the kernels are not compared with this LLVM\'s' % (version, third, words[2], words[3]))
        sys.exit(2)
    third = words9[3] >> 18 & 0x1ff
    if third:
        print('llvm-mc %s writes 0x%02x for gfx9 in the third source a two-source instruction does not have (v_pk_min_u16 v1, v2, v3 is %08x %08x), '
              'the build\'s assembler 0: the kernels are not compared with this LLVM\'s' % (version, third, words9[2], words9[3]))
        sys.exit(2)
    print('llvm-mc %s writes the words the build\'s assembler is held to' % version)


def chips(asm, names):
    #   a gfx9 chip is held to gfx900's words, the others to gfx1036's
    for first, held in ((None, [n for n in names if n not in GFX9]), (GFX9[0], [n for n in names if n in GFX9])):
        if not held:
            continue
        ours = kernels(build(asm, first))
        for chip in held:
            theirs = kernels(build(asm, chip))
            if [n for n, _ in theirs] != [n for n, _ in ours]:
                sys.exit('%s: for %s the kernels are %s' % (asm, chip, [n for n, _ in theirs]))
            for (name, a), (_, b) in zip(ours, theirs):
                bad = [i for i in range(max(len(a), len(b))) if i >= len(a) or i >= len(b) or a[i] != b[i]]
                if bad:
                    sys.exit('%s: kernel %s is not the same words for %s as for %s: %d differ, the first at word %d'
                             % (asm, name, chip, first or 'gfx1036', len(bad), bad[0]))
        print('gpu kernels: %s is the same %d words for %s and for %s'
              % (asm, sum(len(w) for _, w in ours), first or 'gfx1036', ', '.join(held)))


def sections(d):
    shoff = struct.unpack_from('<Q', d, 0x28)[0]
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', d, 0x3A)
    secs = []
    for i in range(shnum):
        name, typ, flags, addr, off, size, link, info, align, entsize = struct.unpack_from('<IIQQQQIIQQ', d, shoff + i * shentsize)
        secs.append((name, typ, addr, off, size, link))
    return secs


def kernels(d):
    secs = sections(d)
    symtab = next(s for s in secs if s[1] == 2)
    strtab = secs[symtab[5]]
    syms = {}
    for i in range(symtab[4] // 24):
        name, info, other, shndx, value, size = struct.unpack_from('<IBBHQQ', d, symtab[3] + i * 24)
        syms[d[strtab[3] + name:d.index(b'\0', strtab[3] + name)].decode()] = (value, size, shndx)
    out = []
    #   the kernels, in the order their descriptors lie in the object
    for name in sorted((n[:-3] for n in syms if n.endswith('.kd')), key=lambda n: (syms[n + '.kd'][2], syms[n + '.kd'][0])):
        kd_addr, _, kd_sec = syms[name + '.kd']
        fn_addr, fn_size, fn_sec = syms[name]
        ro = secs[kd_sec]
        at = ro[3] + kd_addr - ro[2]
        kd = d[at:at + 64]
        privately = struct.unpack_from('<I', kd, 4)[0]
        if privately:
            sys.exit('%s needs scratch (%d bytes): the dispatch gives none' % (name, privately))
        rsrc1, rsrc2 = struct.unpack_from('<II', kd, 48)
        tx = secs[fn_sec]
        code = d[tx[3] + fn_addr - tx[2]:tx[3] + fn_addr - tx[2] + fn_size]
        out.append((name, [rsrc1, rsrc2] + list(struct.unpack('<%dI' % (len(code) // 4), code))))
    return out


def arrays(text, prefix=''):
    if prefix:
        return [(name, [int(w, 16) for w in re.findall(r'0x[0-9a-f]+', body)])
                for name, body in re.findall(r'static const unsigned int gpu_k_' + re.escape(prefix) + r'(\w+)\[\] = \{(.*?)\};', text, re.S)]
    return [(name, [int(w, 16) for w in re.findall(r'0x[0-9a-f]+', body)])
            for name, body in re.findall(r'static const unsigned int gpu_k_(?!11_|12_|9_)(\w+)\[\] = \{(.*?)\};', text, re.S)]


def asm_hash(asm):
    h = 0xcbf29ce484222325
    for c in pathlib.Path(asm).read_bytes():
        h = ((h ^ c) * 0x100000001b3) & 0xffffffffffffffff
    return h


def text(made, asm=None, prefix=''):
    lines = ['#define GPU_KERNELS_ASM_HASH 0x%016xull // the FNV-1a 64 of the gpu.asm these were made of (gpu.c holds it to gpu_asm.hash)\n' % asm_hash(asm)] if asm else []
    for name, words in made:
        lines.append('static const unsigned int gpu_k_%s%s[] = {\n' % (prefix, name))
        for i in range(0, len(words), 10):
            lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 10]) + (',' if i + 10 < len(words) else '};') + '\n')
    return ''.join(lines)


def check_regs(asm):
    src = pathlib.Path(asm).read_text()
    macros, cur_m, decls = {}, None, {}
    for line in src.splitlines():
        s = line.split(';', 1)[0].strip()
        if not s:
            continue
        if s.startswith('.macro '):
            cur_m = s.split()[1].rstrip(',')
            macros[cur_m] = []
        elif s == '.endm':
            cur_m = None
        elif cur_m is not None:
            macros[cur_m].append(s)
        m = re.match(r'kernel\s+(\w+)\s*,\s*(\d+)\s*,\s*(\d+)', s)
        if m:
            decls[m.group(1)] = (int(m.group(2)), int(m.group(3)))
    cur_k, k_lines = None, {}
    for line in src.splitlines():
        s = line.split(';', 1)[0].strip()
        if cur_k is None:
            m = re.match(r'^(\w+):$', s)
            if m and m.group(1) in decls:
                cur_k = m.group(1)
                k_lines[cur_k] = []
        elif re.match(r'^\.size\s+' + re.escape(cur_k) + r'\s*,', s):
            cur_k = None
        elif s:
            k_lines[cur_k].append(s)

    def scan(lines, seen):
        vg, sg = -1, -1
        for s in lines:
            op = s.split()[0]
            if op in macros and op not in seen:
                mv, ms = scan(macros[op], seen | {op})
                vg, sg = max(vg, mv), max(sg, ms)
            for a, b in re.findall(r'\bv\[(\d+):(\d+)\]', s):
                vg = max(vg, int(a), int(b))
            for a in re.findall(r'\bv(\d+)\b', s):
                vg = max(vg, int(a))
            for a, b in re.findall(r'\bs\[(\d+):(\d+)\]', s):
                for r in (int(a), int(b)):
                    if r <= 105:
                        sg = max(sg, r)
            for a in re.findall(r'\bs(\d+)\b', s):
                r = int(a)
                if r <= 105:
                    sg = max(sg, r)
        return vg, sg

    for name, (nv, ns) in decls.items():
        if name not in k_lines:
            continue
        vg, sg = scan(k_lines[name], set())
        if vg >= nv:
            sys.exit('%s: kernel %s uses v%d, exceeding .amdhsa_next_free_vgpr %d' % (asm, name, vg, nv))
        if sg >= ns:
            sys.exit('%s: kernel %s uses s%d, exceeding .amdhsa_next_free_sgpr %d' % (asm, name, sg, ns))


def intel_kernels(src_text):
    """The Intel kernels of src/canvas/gpu_i915.asm: kernel NAME, then the words, comma separated, comments after ';'."""
    kernels, name = [], None
    for raw in src_text.splitlines():
        line = raw.split(';', 1)[0].strip()
        if not line:
            continue
        if line.startswith('kernel '):
            name = line.split()[1]
            kernels.append((name, []))
            continue
        if name is None or not re.fullmatch(r'0x[0-9a-fA-F]+(\s*,\s*0x[0-9a-fA-F]+)*\s*,?', line):
            sys.exit('gpu_i915.asm: not a kernel word line: %r' % raw)
        kernels[-1][1].extend(int(w, 16) for w in re.findall(r'0x[0-9a-fA-F]+', line))
    return kernels


def intel_gen12(text):
    """A kernel's Gen9 assembly (src/canvas/gpu_i915_NAME.iga) in Gen12's syntax, which differs in the sends alone: the shared function is
    in the mnemonic (send.dc1 the data port's block messages, send.ts the end of thread), a send has two sources (the second null here) and
    its extended descriptor an operand of its own, and a destination nothing is written to is null:ud. Three words change with it, as on
    the card: a 16-byte block's write is the header and one register (0x040A8000: gpu.c's Gen11 patch of the Gen9 words says the same), the
    block's byte offset is a shift (no dword by dword multiply after Gen9), and the word that makes a send's descriptor in a0.0, and every
    jmpi, is written without the mask (W). The dependencies (Gen12's software scoreboard) are iga64's own (-Xauto-deps): it also puts the
    syncs after a send that ends a block. A send this does not know stops the conversion."""
    out = []
    for raw in text.splitlines():
        code, sep, note = raw.partition('//')
        m = re.match(r'^(\s*)send\s+\((\d+)\|M0\)\s+(\S+)\s+(\S+)\s+(0x[0-9A-Fa-f]+)\s+(\S+)\s*(\{EOT\})?\s*$', code)
        if m:
            lead, width, dst, src, sfid, desc, eot = m.groups()
            dst = 'null:ud' if dst.split(':')[0] in ('null', 'acc0') else dst
            src = src.split(':')[0] + ':ud'
            if desc.lower() == '0x060a8000':
                desc = '0x040A8000'
            if int(sfid, 16) == 0x27 and eot and dst == 'null:ud':
                code = '%ssend.ts (%s|M0)          null:ud       %-9s null:ud  0x0  %s {EOT}' % (lead, width, src, desc)
            elif int(sfid, 16) == 0xC and not eot:
                code = '%ssend.dc1 (%s|M0)         %-13s %-9s null:ud  0x0  %s' % (lead, width, dst, src, desc)
            else:
                sys.exit('--intel-gen12: a send this conversion does not know: %r' % raw)
        elif re.match(r'^\s*(\([^)]*\)\s*)?sends?c?\b', code):
            sys.exit('--intel-gen12: a send this conversion does not know: %r' % raw)
        else:
            code = re.sub(r'^(\s*)mul (\(1\|M0\)\s+r2\.0<1>:ud\s+r0\.1<0;1,0>:ud\s+)0x10:ud', r'\1shl \g<2>4:ud', code)
            code = re.sub(r'^(\s*)or \(1\|M0\)(\s+a0\.0<1>:ud)', r'\1(W) or (1|M0)\2', code)
            code = re.sub(r'^(\s*)\((f[01]\.[01])\) jmpi(?: \(1\|M0\))?\s', r'\1(W&\2) jmpi ', code)
            code = re.sub(r'^(\s*)jmpi(?: \(1\|M0\))?\s', r'\1(W) jmpi ', code)
        out.append(code.rstrip() + ('  //' + note if sep and code.strip() else sep + note))
    return '\n'.join(out) + '\n'


