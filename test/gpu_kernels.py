# The order of the Intel set's kernels in the source, and the words the source's kernels are held to: each the iga64 assembly of its .iga (fill is IGT's,
# above). bx has words and no encoder yet; the array the build writes for it is checked like the rest.
INTEL_GEN9_ORDER = ['copy', 'fill', 'tone', 'glass', 'bx', 'scene', 'cp', 'scale']
INTEL_LITERALS = {'copy': COPY_GEN9_WORDS, 'tone': TONE_GEN9_WORDS, 'glass': GLASS_GEN9_WORDS, 'scene': SCENE_GEN9_WORDS, 'cp': CP_GEN9_WORDS,
                  'bx': BX_GEN9_WORDS, 'scale': SCALE_GEN9_WORDS}
# Gen12's set after it, a kernel NAME12 for each NAME: its .iga in Gen12's syntax (--intel-gen12; the fill's is src/canvas/gpu_i915_fill.iga, IGT's
# Gen9 rows as iga64 reads them) assembled by iga64 -a -p=12p1 -Xauto-deps -Xforce-no-compact.
INTEL_ORDER = INTEL_GEN9_ORDER + [name + '12' for name in INTEL_GEN9_ORDER]
INTEL_LITERALS.update({'copy12': COPY_GEN12_WORDS, 'fill12': FILL_GEN12_WORDS, 'tone12': TONE_GEN12_WORDS, 'glass12': GLASS_GEN12_WORDS,
                       'bx12': BX_GEN12_WORDS, 'scene12': SCENE_GEN12_WORDS, 'cp12': CP_GEN12_WORDS, 'scale12': SCALE_GEN12_WORDS})


def intel_check(src, inc):
    listed = intel_kernels(pathlib.Path(src).read_text())
    kernels = dict(listed)
    if [n for n, _ in listed] != INTEL_ORDER:
        sys.exit('%s: the kernels are %s, the Gen9 and Gen12 sets have %s' % (src, [n for n, _ in listed], ', '.join(INTEL_ORDER)))
    for name, lit in INTEL_LITERALS.items():
        if kernels[name] != lit:
            sys.exit('%s: %s differs from the iga64 assembly of gpu_i915_%s.iga (%d words, the reviewed kernel has %d)' % (src, name, name[:-2] if name.endswith('12') else name, len(kernels[name]), len(lit)))
    fill = kernels['fill']
    if fill != IGT_GEN9_FILL_ROWS_1_TO_9:
        bad = [i for i in range(max(len(fill), 36)) if i >= len(fill) or i >= 36 or fill[i] != IGT_GEN9_FILL_ROWS_1_TO_9[i]]
        sys.exit('%s: fill differs from IGT at word %d (%s)' % (src, bad[0], 'missing' if bad[0] >= len(fill) else '%08x vs IGT' % fill[bad[0]]))
    made = intel_arrays(pathlib.Path(inc).read_text())
    if [n for n, _ in made] != INTEL_ORDER:
        sys.exit('%s: the arrays are %s, the source has %s' % (inc, [n for n, _ in made], ', '.join(INTEL_ORDER)))
    for name, words in made:
        if words != kernels[name]:
            sys.exit('%s: the array %s is not the source\'s words' % (inc, name))
    print('gpu i915 kernels: %s, copy the iga64 assembly of gpu_i915_copy.iga, fill the same as IGT rows 1 to 9, tone, glass, bx, cp, scene and scale the iga64 assembly, the eight of Gen12 (NAME12) iga64\'s of the same sources in Gen12\'s syntax, all as %s' % (src, inc))


def main():
    if len(sys.argv) == 5 and sys.argv[1] == '--target' and sys.argv[2] == 'intel-gen9':
        intel_check(sys.argv[3], sys.argv[4])
        return
    if len(sys.argv) == 3 and sys.argv[1] == '--print-intel':
        sys.stdout.write(intel_text(intel_kernels(pathlib.Path(sys.argv[2]).read_text())))
        return
    if len(sys.argv) == 3 and sys.argv[1] == '--intel-gen12':
        sys.stdout.write(intel_gen12(pathlib.Path(sys.argv[2]).read_text()))
        return
    if len(sys.argv) > 3 and sys.argv[1] == '--chips':
        chips(sys.argv[2], sys.argv[3:])
        return
    if len(sys.argv) == 2 and sys.argv[1] == '--probe':
        probe()
        return
    if len(sys.argv) == 3 and sys.argv[1] == '--print':
        sys.stdout.write(text(kernels(build(sys.argv[2])), sys.argv[2]))
        sys.stdout.write(text(kernels(build(sys.argv[2], 'gfx1100')), None, '11_'))
        sys.stdout.write(text(kernels(build(sys.argv[2], 'gfx1200')), None, '12_'))
        sys.stdout.write(text(kernels(build(sys.argv[2], GFX9[0])), None, '9_'))
        return
    if len(sys.argv) == 3 and sys.argv[1] == '--hash':
        sys.stdout.write('// src/canvas/gpu.asm\'s FNV-1a 64: what artifacts/gpu_kernels.inc is held to (gpu.c). Made again with\n'
                         '// python3 -I test/gpu_kernels.py --hash src/canvas/gpu.asm > src/canvas/gpu_asm.hash whenever gpu.asm changes.\n'
                         '#define GPU_ASM_HASH 0x%016xull\n' % asm_hash(sys.argv[2]))
        return
    if len(sys.argv) != 3 or sys.argv[1].startswith('-'):
        sys.exit(__doc__)
    asm, inc = sys.argv[1], sys.argv[2]
    if pathlib.Path(asm).name != 'gpu_stress.asm':
        check_regs(asm)
    inc_text = pathlib.Path(inc).read_text()
    for label, chip, prefix in [('gfx1036', None, ''), ('gfx1100', 'gfx1100', '11_'), ('gfx1200', 'gfx1200', '12_'), (GFX9[0], GFX9[0], '9_')]:
        ours = arrays(inc_text, prefix)
        if prefix and not ours:
            continue
        llvm = kernels(build(asm, chip))
        if [n for n, _ in llvm] != [n for n, _ in ours]:
            sys.exit('%s (%s): the kernels are %s, LLVM has %s' % (inc, label, [n for n, _ in ours], [n for n, _ in llvm]))
        words = 0
        for (name, theirs), (_, mine) in zip(llvm, ours):
            if len(theirs) != len(mine):
                sys.exit('%s (%s): kernel %s is %d words, LLVM makes %d' % (inc, label, name, len(mine), len(theirs)))
            bad = [i for i in range(len(mine)) if mine[i] != theirs[i]]
            if bad:
                i = bad[0]
                sys.exit('%s (%s): kernel %s differs from LLVM in %d of %d words, the first at word %d (code word %d): %08x, LLVM %08x'
                         % (inc, label, name, len(bad), len(mine), i, i - 2, mine[i], theirs[i]))
            words += len(mine)
        print('gpu kernels (%s): %s, %d kernels and %d words, the same as LLVM makes' % (label, asm, len(llvm), words))


